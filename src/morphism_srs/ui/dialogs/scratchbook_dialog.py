DEFAULT_DSL_TEMPLATE = """@course "Algebraic Topology"
@folder "Pure Mathematics/Topology"

@note fundamental_group_def
title: "Definition of the Fundamental Group"
mode: standard
tags: [algebraic_topology, fundamental_group, definition]
---
Q: Define the fundamental group $\\pi_1(X, x_0)$ of a pointed topological space $(X, x_0)$.
A: $\\pi_1(X, x_0)$ is the set of based homotopy classes of loops $[\\gamma]$ at $x_0$ under path concatenation.
---

@note van_kampen_thm
title: "Seifert-van Kampen Theorem"
mode: serial
tags: [algebraic_topology, van_kampen_theorem, theorem, proof]
deps: [fundamental_group_def]
premise: Let $X = U \\cup V$ with $U, V, U \\cap V$ path-connected and $x_0 \\in U \\cap V$.
---
[step 1: Surjectivity of Φ]
Q: Why is the canonical homomorphism $\\Phi: \\pi_1(U) * \\pi_1(V) \\to \\pi_1(X)$ surjective?
A: By Lebesgue's number lemma, any loop $\\gamma: I \\to X$ can be subdivided into subpaths each contained in $U$ or $V$.
[step 2: Kernel Identification]
Q: What is $\\ker(\\Phi)$?
A: It is the normal closure $N$ generated by elements $i_{1*}(w) i_{2*}(w)^{-1}$ for $w \\in \\pi_1(U \\cap V, x_0)$, so $\\pi_1(X) \\cong \\pi_1(U) *_{\\pi_1(U \\cap V)} \\pi_1(V)$.
---
"""


class ScratchbookDialog(QDialog):
    """Scratchbook & Live .mdsl Compiler Studio with SQLite page persistence and MathJax preview."""

    def __init__(
        self,
        conn: sqlite3.Connection,
        web_profile: WebEngineProfileManager,
        event_bus: EventBus,
        parent: QWidget | None = None,
    ) -> None:
        super().__init__(parent)
        self.setWindowTitle("Scratchbook & .mdsl Compiler Studio")
        apply_relative_geometry(self, width_ratio=0.84, height_ratio=0.82, min_width=840, min_height=540)

        self.conn = conn
        self.web_profile = web_profile
        self.event_bus = event_bus
        self.scratch_repo = ScratchRepository(conn)
        self.dsl_compiler = DSLCompiler(conn)

        self._pages: list[ScratchbookPageModel] = []
        self._active_page: ScratchbookPageModel | None = None
        self._preview_ready = False

        self._debounce = QTimer(self)
        self._debounce.setSingleShot(True)
        self._debounce.setInterval(260)
        self._debounce.timeout.connect(self._on_auto_save_and_preview)

        self._build_ui()
        self._load_pages()

    def _build_ui(self) -> None:
        root = QVBoxLayout(self)
        root.setContentsMargins(14, 14, 14, 14)
        root.setSpacing(10)

        top_bar = QHBoxLayout()
        title_lbl = QLabel("Scratchbook & Morphism DSL (.mdsl) Studio", self)
        set_widget_props(title_lbl, role="title")
        top_bar.addWidget(title_lbl)
        top_bar.addStretch(1)

        check_btn = QPushButton("Validate .mdsl", self)
        check_btn.clicked.connect(self._on_validate_dsl)
        compile_btn = QPushButton("Compile .mdsl to Course & DAG", self)
        set_widget_props(compile_btn, variant="primary")
        compile_btn.clicked.connect(self._on_compile_dsl)
        top_bar.addWidget(check_btn)
        top_bar.addWidget(compile_btn)
        root.addLayout(top_bar)

        splitter = QSplitter(Qt.Orientation.Horizontal, self)

        # Left sidebar: Pages list
        left_widget = QWidget(splitter)
        left_layout = QVBoxLayout(left_widget)
        left_layout.setContentsMargins(0, 0, 6, 0)
        page_btns = QHBoxLayout()
        new_btn = QPushButton("+ Page", left_widget)
        new_btn.clicked.connect(self._on_new_page)
        del_btn = QPushButton("Delete", left_widget)
        del_btn.clicked.connect(self._on_delete_page)
        page_btns.addWidget(new_btn)
        page_btns.addWidget(del_btn)
        left_layout.addLayout(page_btns)

        self.page_list = QListWidget(left_widget)
        self.page_list.currentRowChanged.connect(self._on_page_selected)
        left_layout.addWidget(self.page_list, 1)

        # Middle: Editor + Diagnostics
        mid_widget = QWidget(splitter)
        mid_layout = QVBoxLayout(mid_widget)
        mid_layout.setContentsMargins(4, 0, 4, 0)
        self.editor = QPlainTextEdit(mid_widget)
        self.editor.setPlaceholderText("Write freeform LaTeX notes or @course / @note .mdsl blocks here...")
        self.editor.textChanged.connect(lambda: self._debounce.start())
        mid_layout.addWidget(self.editor, 4)

        self.diag_label = QLabel("Ready.", mid_widget)
        set_widget_props(self.diag_label, role="muted")
        self.diag_label.setWordWrap(True)
        mid_layout.addWidget(self.diag_label)

        # Right: Live MathJax Preview
        right_frame = QFrame(splitter)
        set_widget_props(right_frame, role="panel")
        right_layout = QVBoxLayout(right_frame)
        right_layout.setContentsMargins(6, 6, 6, 6)
        self.web_view = self.web_profile.create_web_view(right_frame)
        self.web_view.loadFinished.connect(self._on_web_loaded)
        self.web_view.setUrl(QUrl("morphism://app/html/preview.html"))
        right_layout.addWidget(self.web_view, 1)

        splitter.addWidget(left_widget)
        splitter.addWidget(mid_widget)
        splitter.addWidget(right_frame)
        splitter.setStretchFactor(0, 1)
        splitter.setStretchFactor(1, 3)
        splitter.setStretchFactor(2, 3)
        root.addWidget(splitter, 1)

    def _load_pages(self) -> None:
        self._pages = self.scratch_repo.list_all()
        if not self._pages:
            with UnitOfWork(self.conn):
                created = self.scratch_repo.create(
                    ScratchbookPageModel(title="Sample .mdsl Deck", content_text=DEFAULT_DSL_TEMPLATE, display_order=0)
                )
            self._pages = [created]

        self.page_list.blockSignals(True)
        self.page_list.clear()
        for p in self._pages:
            self.page_list.addItem(QListWidgetItem(p.title))
        self.page_list.blockSignals(False)
        self.page_list.setCurrentRow(0)
        self._on_page_selected(0)

    def _on_page_selected(self, row: int) -> None:
        if 0 <= row < len(self._pages):
            self._active_page = self._pages[row]
            self.editor.blockSignals(True)
            self.editor.setPlainText(self._active_page.content_text)
            self.editor.blockSignals(False)
            self._on_auto_save_and_preview()

    def _on_new_page(self) -> None:
        title, ok = QInputDialog.getText(self, "New Scratchbook Page", "Page Title:", text="New Page")
        if not ok or not title.strip():
            return
        with UnitOfWork(self.conn):
            p = self.scratch_repo.create(
                ScratchbookPageModel(title=title.strip(), content_text=DEFAULT_DSL_TEMPLATE, display_order=len(self._pages))
            )
        self._pages.append(p)
        self.page_list.addItem(QListWidgetItem(p.title))
        self.page_list.setCurrentRow(len(self._pages) - 1)

    def _on_delete_page(self) -> None:
        if len(self._pages) <= 1 or self._active_page is None or self._active_page.id is None:
            return
        with UnitOfWork(self.conn):
            self.scratch_repo.delete(self._active_page.id)
        self._load_pages()

    def _on_web_loaded(self, ok: bool) -> None:
        self._preview_ready = ok
        if ok:
            self._on_auto_save_and_preview()

    def _on_auto_save_and_preview(self) -> None:
        raw = self.editor.toPlainText()
        if self._active_page is not None and self._active_page.id is not None:
            self._active_page.content_text = raw
            with UnitOfWork(self.conn):
                self.scratch_repo.update(self._active_page)

        if not self._preview_ready:
            return

        if "@note" in raw or "@course" in raw:
            res = self.dsl_compiler.check_only(raw)
            if res.diagnostics:
                d0 = res.diagnostics[0]
                self.diag_label.setText(f"[{d0.severity.upper()} Line {d0.line_num}] {d0.message} ({len(res.diagnostics)} issue(s))")
            else:
                self.diag_label.setText(f"Valid .mdsl: {len(res.ast.notes)} note(s) ready to compile.")
            cards_preview = []
            for n in res.ast.notes:
                for c in n.cards:
                    cards_preview.append(
                        {
                            "title": f"{n.title} — {c.title}" if c.title else n.title,
                            "front_html": sanitize_math_html(c.front),
                            "back_html": sanitize_math_html(c.back),
                            "hint_html": sanitize_math_html(c.hint),
                        }
                    )
            payload = {
                "title": res.ast.course_name or (self._active_page.title if self._active_page else "DSL Preview"),
                "review_mode": "serial" if any(n.mode == "serial" for n in res.ast.notes) else "standard",
                "tags": [],
                "premise_html": "",
                "cards": cards_preview,
            }
        else:
            self.diag_label.setText("Freeform LaTeX / HTML scratchpad mode.")
            payload = {
                "title": self._active_page.title if self._active_page else "Scratchpad",
                "review_mode": "standard",
                "tags": [],
                "premise_html": "",
                "cards": [
                    {
                        "title": "Notes",
                        "front_html": sanitize_math_html(raw).replace("\n", "<br>"),
                        "back_html": "",
                        "hint_html": "",
                    }
                ],
            }

        self.web_view.page().runJavaScript(
            f"if (window.MorphismPreview) {{ window.MorphismPreview.renderPreview({json.dumps(payload)}); }}"
        )

    def _on_validate_dsl(self) -> None:
        res = self.dsl_compiler.check_only(self.editor.toPlainText())
        if not res.diagnostics:
            QMessageBox.information(self, "DSL Validation Passed", f"No issues found! {len(res.ast.notes)} note(s) parsed cleanly.")
        else:
            msg = "\n".join(f"• [{d.severity.upper()} L{d.line_num}] {d.message}" for d in res.diagnostics[:15])
            QMessageBox.warning(self, "DSL Diagnostics", msg)

    def _on_compile_dsl(self) -> None:
        res = self.dsl_compiler.compile_and_commit(self.editor.toPlainText(), auto_layout=True)
        if res.has_errors:
            msg = "\n".join(f"• [ERROR L{d.line_num}] {d.message}" for d in res.diagnostics if d.severity == "error")
            QMessageBox.critical(self, "Compilation Failed", msg)
            return
        self.event_bus.courses_updated.emit()
        if res.course_id is not None:
            self.event_bus.notes_updated.emit(res.course_id)
        QMessageBox.information(
            self,
            "DSL Compiled Successfully",
            f"Course ID #{res.course_id}:\n"
            f"• Notes created: {res.notes_created}\n"
            f"• Notes updated: {res.notes_updated}\n"
            f"• Dependency edges created: {res.edges_created}",
        )
